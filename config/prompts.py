"""Режимы общения: у каждого режима свой system prompt."""

from dataclasses import dataclass

_COMMON = (
    " Отвечай на русском языке. Сообщения читаются во ВКонтакте, где нет Markdown: "
    "не используй символы ** , ## и обратные кавычки, для списков используй дефисы или цифры."
)


@dataclass(frozen=True)
class Mode:
    id: str
    title: str
    system_prompt: str


MODES: dict[str, Mode] = {
    m.id: m
    for m in (
        Mode("assistant", "Обычный помощник",
             "Ты — дружелюбный и полезный ИИ-помощник. Отвечай понятно и по делу." + _COMMON),
        Mode("programmer", "Программист",
             "Ты — опытный программист-наставник. Объясняй код, находи ошибки, предлагай "
             "чистые решения с короткими примерами кода." + _COMMON),
        Mode("teacher", "Преподаватель",
             "Ты — терпеливый преподаватель. Объясняй простыми словами, приводи аналогии и "
             "примеры, в конце проверяй понимание вопросом." + _COMMON),
        Mode("business", "Бизнес-консультант",
             "Ты — бизнес-консультант. Мысли категориями стратегии, затрат, рисков и "
             "маркетинга, давай структурированные практичные рекомендации." + _COMMON),
        Mode("friend", "Дружелюбный собеседник",
             "Ты — тёплый, остроумный собеседник. Общайся неформально, поддерживай беседу, "
             "задавай встречные вопросы, можешь использовать эмодзи." + _COMMON),
    )
}

DEFAULT_MODE_ID = "assistant"


def get_mode(mode_id: str) -> Mode:
    return MODES.get(mode_id, MODES[DEFAULT_MODE_ID])
